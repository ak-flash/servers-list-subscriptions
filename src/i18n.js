function parseCookies(value) {
  return String(value || '').split(';').reduce((result, part) => {
    const index = part.indexOf('=');
    if (index > 0) result[part.slice(0, index).trim()] = decodeURIComponent(part.slice(index + 1).trim());
    return result;
  }, {});
}

function detectLocale(req) {
  const query = typeof req.query?.lang === 'string' ? req.query.lang.toLowerCase() : '';
  const cookie = parseCookies(req.headers.cookie).locale?.toLowerCase();
  const accepted = String(req.headers['accept-language'] || '').toLowerCase().split(',').map(value => value.split(';')[0].split('-')[0]);
  return supportedLocales.includes(query) ? query : supportedLocales.includes(cookie) ? cookie : accepted.find(value => supportedLocales.includes(value)) || 'ru';
}

function createTranslator(locale) {
  return (key, values = {}) => {
    let text = dictionaries[locale][key] || key;
    return text.replace(/\{(\w+)\}/g, (_, name) => values[name] === undefined ? '' : String(values[name]));
  };
}

function languageUrl(req, locale) {
  const query = new URLSearchParams(req.query);
  query.set('lang', locale);
  return `${req.path}?${query}`;
}

function i18n(req, res, next) {
  const locale = detectLocale(req);
  if (typeof req.query?.lang === 'string' && supportedLocales.includes(req.query.lang.toLowerCase())) {
    res.cookie('locale', locale, { maxAge: 31536000000, httpOnly: false, sameSite: 'lax' });
  }
  res.locals.locale = locale;
  res.locals.t = createTranslator(locale);
  req.locale = locale;
  req.t = res.locals.t;
  res.locals.languageUrl = value => languageUrl(req, value);
  next();
}

